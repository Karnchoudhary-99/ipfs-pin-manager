// Garbage collection planning: find node pins the registry does not track,
// and turn them into a safe, reviewable sweep.
//
// This tool never unpins anything on a node by itself — there is no IPFS
// client here, and silently deleting content would be the worst possible
// default for a pin manager. `planGc` only reports candidates; `gc` in
// the CLI prints the plan, and optionally writes the `ipfs pin rm`
// commands as a shell script for the operator to review and run.
// The one mutation offered is --prune-dangling on the LOCAL registry:
// dropping registry entries for content the node no longer pins, which
// is explicit, local, and reversible from the store's git history.
//
// Sizes: a candidate's reclaimable bytes are known only when the caller
// supplies a size map (cid -> bytes, e.g. from `ipfs dag stat` or a
// blockstore walk). Without a size for every candidate, the total is
// reported with sizeComplete: false, never silently partial.

/** Candidates = node pins absent from the registry, in node order, deduped. */
export function planGc(registry, nodeCids, sizes = {}) {
  const registrySet = new Set(registry.list().map((p) => p.cid));
  const candidates = [];
  for (const cid of nodeCids) {
    if (!registrySet.has(cid) && !candidates.includes(cid)) candidates.push(cid);
  }
  let reclaimableBytes = 0;
  let sizeComplete = true;
  for (const cid of candidates) {
    const size = sizes[cid];
    if (size === undefined || !Number.isInteger(size) || size < 0) sizeComplete = false;
    else reclaimableBytes += size;
  }
  return { candidates, reclaimableBytes, sizeComplete, candidateCount: candidates.length };
}

/** Shell script (ipfs pin rm, one per candidate) for operator review. */
export function formatGcScript(plan) {
  const header = [
    "#!/bin/sh",
    "# Generated by ipfs-pin-manager: review before running.",
    "# Removes only the untracked (extra) pins from the GC plan.",
    "set -e",
  ];
  if (plan.candidates.length === 0) {
    return [...header, "# No orphaned pins: nothing to remove."].join("\n") + "\n";
  }
  return [...header, ...plan.candidates.map((cid) => `ipfs pin rm ${cid}`)].join("\n") + "\n";
}

/**
 * Remove registry entries for content the node no longer pins, and
 * return the pruned CIDs. Callers save the store afterwards.
 */
export function pruneDangling(registry, nodeCids) {
  const nodeSet = new Set(nodeCids);
  const pruned = [];
  for (const pin of registry.list()) {
    if (!nodeSet.has(pin.cid)) {
      registry.unpin(pin.cid);
      pruned.push(pin.cid);
    }
  }
  return pruned;
}
